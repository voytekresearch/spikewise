# 2. COMPARE EFFECT SIZES
# ==========================================

def plot_population_effect_sizes(df_stats, feature_shades):
    """
    Generates a statistical summary table and plots the population distribution 
    of effect sizes (Cohen's d) for each LFP feature.

    The summary table aggregates the total number of significant windows and 
    ranks them dynamically by the median effect size. The visualization pairs 
    a boxplot with a stripplot to show both the distribution and individual data points.

    Parameters
    ----------
    df_stats : pandas.DataFrame
        The master statistics DataFrame generated by `compile_lfp_stats`.
    feature_shades : dict
        A dictionary mapping the spike feature string names (e.g., 'peak_width_cluster') 
        to specific hex color codes for consistent plotting.
    """
    warnings.filterwarnings('ignore', category=FutureWarning)

    # 1. Print a quick summary table, RANKED BY MEDIAN EFFECT SIZE
    print("=== SIGNIFICANT HITS SUMMARY ===")
    summary_table = (
        df_stats.groupby(['lfp_feature', 'spike_feature'])
        .agg(
            sig_windows_count=('cohens_d', 'size'),      # Count how many hits
            median_cohens_d=('cohens_d', 'median')       # Calculate median effect size
        )
        .reset_index()
        .sort_values(by='median_cohens_d', ascending=False) # Sort by largest median effect
        .reset_index(drop=True)
    )
    display(summary_table)

    # 2. Plot the Effect Sizes
    plt.figure(figsize=(14, 6))

    sns.boxplot(
        data=df_stats, 
        x="lfp_feature", 
        y="cohens_d", 
        hue="spike_feature", 
        palette=feature_shades, 
        width=0.7,
        fliersize=0
    )

    sns.stripplot(
        data=df_stats, 
        x="lfp_feature", 
        y="cohens_d", 
        hue="spike_feature",
        dodge=True,
        palette="dark:black", 
        alpha=0.5, 
        jitter=True,
        legend=False
    )

    plt.title("Population Effect Sizes", fontweight="bold", fontsize=14)
    plt.ylabel("Effect Size (Cohen's d)")
    plt.xlabel("LFP Feature")
    plt.xticks(rotation=15)
    plt.legend(title="Spike Feature", bbox_to_anchor=(1.02, 1), loc='upper left')
    plt.tight_layout()
    plt.show()


